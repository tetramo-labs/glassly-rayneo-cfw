/* One lens scene (G2 parity: the phone keeps a left and a right mirror and
 * sends each lens its own SHOW once any element has depth). Assets live in
 * the shared store; objects, the active set, the background and the settle
 * state are per lens, as is the L8 canvas the display thread composes from. */
typedef struct {
    uint8_t bit;                   /* LENS_LEFT / LENS_RIGHT */
    uint8_t *canvas;               /* L8 CFW_W x CFW_H; UI thread draws, display thread converts */
    /* static-layer cache (revision 9): the objects before the first animating
     * one in z order, rendered once per scene change into `base`, so an
     * animation frame costs a copy plus the moving objects */
    uint8_t *base;                 /* L8 CFW_W x CFW_H, NULL when the heap had none (full renders) */
    uint8_t base_valid;
    uint8_t canvas_valid;
    uint32_t canvas_serial;         /* scene_serial last drawn into this canvas */
    uint16_t base_count;           /* objects `base` holds (the static prefix) */
    uint32_t base_serial;          /* scene_serial `base` was rendered at */
    uint32_t scene_serial;         /* bumped by every message and takeover touching this lens */
    cfw_object objects[CACHE_OBJECTS];
    uint16_t active_list[CACHE_OBJECTS];
    uint16_t active_count;
    uint8_t bg;                    /* background gray of the last SHOW */
    uint8_t raster;                /* a raster frame owns the canvas: nothing re-renders it until a SHOW/HIDE (raster.c) */
    uint8_t last_show_valid;
    uint8_t settle_pending;        /* a tagged SHOW has not reported SETTLED yet */
    uint16_t settle_tag;
    uint16_t last_show_request;    /* a repeated SHOW/HIDE request id is acknowledged, not re-applied */
    /* cache journal (STATE replies): every definition, completion, eviction
     * and drop this lens's phone mirror must learn about */
    uint32_t revision;             /* mutation counter, journaled; the REPLY's revision word */
    uint32_t journal_lost_rev;     /* highest revision overwritten out of the ring */
    uint8_t journal_head, journal_count;
    uint8_t mutated;               /* a note landed while applying the current message */
    cfw_journal_entry journal[CACHE_JOURNAL];
} cfw_lens;

