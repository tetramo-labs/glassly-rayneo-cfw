/* little-endian store helpers (shared) */
static inline void cfw_put16(uint8_t *p, uint16_t v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); }
static inline void cfw_put32(uint8_t *p, uint32_t v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); p[2] = (uint8_t)(v >> 16); p[3] = (uint8_t)(v >> 24); }

/* ---- firmware call wrappers ------------------------------------------------
 * Each firmware entry point is an absolute Thumb function-pointer constant whose
 * address came from the verified symbol table (fw_syms.h). The low bit is the
 * Thumb state bit (addresses in the table already carry it). */
#define FW(sig, addr) ((sig)(uintptr_t)(addr))

